import { Divider, Image, Typography, Upload } from "antd";
import { InboxOutlined, LoadingOutlined } from "@ant-design/icons";

import { useDetector } from "@hooks/useDetector";
import { Header } from "@components/Header";
import { Footer } from "@components/Footer";

export default function App() {
  const { detectImage, loading, result, imageSrc } = useDetector();

  return (
    <>
      <Header />
      <div className="w-full h-(--screen-height) p-3">
        <div className="max-w-md mx-auto">
          <Typography.Title>AI Image detector</Typography.Title>
          <Typography.Paragraph type="secondary">
            Select an image, and the app will tell you how likely it is to have
            been generated by AI.
          </Typography.Paragraph>
          <Divider />
          <Upload.Dragger
            beforeUpload={(file) => {
              detectImage(file);
              return false;
            }}
            showUploadList={false}
            accept={"image/jpeg, image/png, image/webp"}
            maxCount={1}
          >
            {loading && (
              <div className="py-9">
                <p className="mb-3!">
                  <LoadingOutlined className="text-3xl mb-3" />
                </p>
                <Typography.Paragraph className="mb-0!">
                  Detectiong...
                </Typography.Paragraph>
              </div>
            )}
            {!loading && !imageSrc ? (
              <>
                <p className="ant-upload-drag-icon">
                  <InboxOutlined />
                </p>
                <Typography.Paragraph>
                  Click or drag file to this area to upload
                </Typography.Paragraph>
                <Typography.Paragraph type="secondary">
                  Support for a single upload. Strictly prohibited from
                  uploading company data or other banned files.
                </Typography.Paragraph>
              </>
            ) : null}
            {!loading && imageSrc ? (
              <>
                <Typography.Paragraph className="mb-3! text-lg!">
                  🤖 photo is {((result?.confidence ?? 0) * 100).toFixed(2)}% AI-generated.
                </Typography.Paragraph>
                <Image
                  src={imageSrc}
                  classNames={{
                    root: "w-full! bg-(--bg) rounded-xl",
                    image: "aspect-4/3 object-contain",
                  }}
                  preview={false}
                />
              </>
            ) : null}
          </Upload.Dragger>
        </div>
      </div>
      <Footer />
    </>
  );
}
